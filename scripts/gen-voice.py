# Renders the tutorial narration with Kokoro-82M (local, Apache-2.0 neural TTS)
# into assets/tutorial/*.m4a and writes src/tutorial/voice.ts.
#
#   python3 -m venv .tts && .tts/bin/pip install kokoro-onnx soundfile
#   .tts/bin/python scripts/gen-voice.py ~/.cache/hyperframes/tts
#
# The model dir needs models/kokoro-v1.0.onnx and voices/voices-v1.0.bin
# (`npx hyperframes tts` downloads both). Uses macOS `afconvert` for AAC.
import json, os, subprocess, sys, tempfile

import espeakng_loader
import soundfile as sf
from kokoro_onnx import Kokoro
from kokoro_onnx.config import EspeakConfig

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODEL_DIR = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else '~/.cache/hyperframes/tts')
VOICES = {'en': ('af_heart', 'en-us', 1.0), 'hi': ('hf_alpha', 'hi', 0.95)}

lines = json.load(open(os.path.join(ROOT, 'src/tutorial/narration.json'), encoding='utf-8'))
kokoro = Kokoro(
    os.path.join(MODEL_DIR, 'models/kokoro-v1.0.onnx'),
    os.path.join(MODEL_DIR, 'voices/voices-v1.0.bin'),
    espeak_config=EspeakConfig(lib_path=espeakng_loader.get_library_path(), data_path=espeakng_loader.get_data_path()),
)
out_dir = os.path.join(ROOT, 'assets/tutorial')
os.makedirs(out_dir, exist_ok=True)

durations = {}
for lang, texts in lines.items():
    voice, phon, speed = VOICES[lang]
    durations[lang] = []
    for i, text in enumerate(texts):
        samples, sr = kokoro.create(text, voice=voice, speed=speed, lang=phon)
        name = f'{lang}-{i + 1:02d}.m4a'
        with tempfile.NamedTemporaryFile(suffix='.wav') as tmp:
            sf.write(tmp.name, samples, sr)
            subprocess.run(['afconvert', '-f', 'm4af', '-d', 'aac', '-b', '64000', tmp.name, os.path.join(out_dir, name)], check=True)
        durations[lang].append(round(len(samples) / sr, 2))
        print(name, durations[lang][-1], 's')

with open(os.path.join(ROOT, 'src/tutorial/voice.ts'), 'w', encoding='utf-8') as f:
    f.write('// Generated by scripts/gen-voice.py — do not edit.\n')
    f.write('\n')
    f.write('export const VOICE = {\n')
    for lang in lines:
        f.write(f'  {lang}: [\n')
        for i, d in enumerate(durations[lang]):
            f.write(f"    {{ clip: require('../../assets/tutorial/{lang}-{i + 1:02d}.m4a'), sec: {d} }},\n")
        f.write('  ],\n')
    f.write('};\n')
print('wrote src/tutorial/voice.ts')
